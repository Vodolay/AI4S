"""The shot list for the demo video, and the numbers it quotes.

The video is a deliverable like the report, so it follows the same rule: every
figure it states comes from `outputs/metrics.json`, interpolated at build time.
A caption cannot quietly disagree with the document it is summarising.

The running order leads with the models, as the app now does: what was asked,
how it was answered, and what the answer turned out not to support. The data
asset follows rather than opening, because a reviewer wants the result before
the shelving. Durations are in seconds and are asserted against the five-minute
limit by a test.
"""

from __future__ import annotations

from dataclasses import dataclass, field

# The three model diagrams are used as the files they already are, not cropped
# out of a screenshot of them. They are generated by `neuromps.report.diagrams`
# for the app, the report and this video alike, so the video gets the original
# at full quality - and does not depend on the slowest part of the app finishing
# its render before the screenshot fires, which is a race it kept losing.
CLASSIFIER_DIAGRAM = "outputs/figures/mechanism_classifier_real.png"
