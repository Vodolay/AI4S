POSTERIOR_RANKS = "outputs/twin/hd14_posterior_ranks_simulated.png"

# Crop boxes into the 1600x2300 app stills, named rather than repeated as
# literals: a mis-typed box is a frame of the wrong thing. All of them sit in
# the top of the page, which is the part that reliably paints.
# Landscape, and close to 16:9 where the panel allows it: a portrait crop is
# letterboxed into the frame and comes out too small to read.
PREDICTION = (40, 1150, 760, 1650)
