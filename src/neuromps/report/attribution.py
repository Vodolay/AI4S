"""Generate CITATIONS.md and THIRD_PARTY.md from what the repository records.

Both files are derived, never hand-maintained: the data citations come from
`data/raw/MANIFEST.json`, which is written by the fetchers at download time, and
the dependency licenses come from the installed package metadata. A test
regenerates them and fails if the committed files have drifted, so a source
added without a license, or a dependency whose license changed, cannot pass
unnoticed.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

log = logging.getLogger("neuromps.report")
REPO_ROOT = Path(__file__).resolve().parents[3]
MANIFEST = REPO_ROOT / "data" / "raw" / "MANIFEST.json"
PYPROJECT = REPO_ROOT / "pyproject.toml"
CITATIONS = REPO_ROOT / "CITATIONS.md"
THIRD_PARTY = REPO_ROOT / "THIRD_PARTY.md"

HEADER = "<!-- Generated by `python -m neuromps.report.attribution`. Do not edit by hand. -->"


def manifest_sources(manifest_path: Path = MANIFEST) -> dict:
    """Sources recorded by the fetchers, keyed by source name."""
    data = json.loads(Path(manifest_path).read_text())
    sources = data.get("sources", data)
    return {k: v for k, v in sources.items() if isinstance(v, dict) and "license" in v}


def render_citations(sources: dict) -> str:
    """CITATIONS.md: every data source, its license, and why it is or is not used."""
    used = {k: v for k, v in sources.items() if v.get("status") != "skipped"}
    skipped = {k: v for k, v in sources.items() if v.get("status") == "skipped"}
    lines = [
        HEADER,
        "",
        "# Data sources and citations",
        "",
        "Per-file URLs, SHA256 hashes and download times are in `data/raw/MANIFEST.json`.",
        "Each fetcher re-checks its source's advertised license at download time.",
        "",
        "## Sources used",
        "",
    ]
    for name, entry in sorted(used.items()):
        lines += _source_block(name, entry)
    if skipped:
        lines += [
            "## Sources deliberately not used",
            "",
            "Recorded here rather than dropped silently: an exclusion on license grounds is a",
            "result about the data landscape, not an omission.",
            "",
        ]
        for name, entry in sorted(skipped.items()):
            lines += _source_block(name, entry)
    return "\n".join(lines).rstrip() + "\n"


def _source_block(name: str, entry: dict) -> list[str]:
    """One source's citation entry."""
    block = [f"### `{name}`", ""]
    block.append(f"- **License:** {entry.get('license', 'UNRECORDED')}")
    if entry.get("license_url"):
        block.append(f"- **License URL:** {entry['license_url']}")
    if entry.get("landing_url"):
        block.append(f"- **Source:** {entry['landing_url']}")
    block.append(f"- **Files recorded:** {len(entry.get('files', []))}")
    block.append(f"- **Status:** {entry.get('status', 'unknown')}")
    if entry.get("citation"):
        block += ["", f"> {entry['citation']}"]
    if entry.get("note"):
        block += ["", f"*Note:* {entry['note']}"]
    return block + [""]


def dependency_licenses(pyproject_path: Path = PYPROJECT) -> list[dict]:
    """Pinned dependencies with the license recorded in their installed metadata."""
    import tomllib
    from importlib import metadata

    config = tomllib.loads(Path(pyproject_path).read_text())
    project = config["project"]
    pinned = list(project.get("dependencies", []))
    for extra in project.get("optional-dependencies", {}).values():
        pinned += list(extra)
    rows = []
    for requirement in sorted(set(pinned), key=str.lower):
        name = requirement.split("==")[0].split(">")[0].split("[")[0].strip()
        version = requirement.split("==")[1].split()[0].strip() if "==" in requirement else ""
        rows.append({"name": name, "pinned": version, "license": _license_of(name, metadata)})
    return rows


def _license_of(name: str, metadata) -> str:
    """License from installed metadata, preferring a classifier over free text."""
    try:
        info = metadata.metadata(name)
    except metadata.PackageNotFoundError:
        return "not installed"
    classifiers = [c for c in info.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return classifiers[0].split("::")[-1].strip()
    declared = (info.get("License-Expression") or info.get("License") or "").strip()
    return declared.splitlines()[0][:60] if declared else "see package"


def render_third_party(rows: list[dict]) -> str:
    """THIRD_PARTY.md: the dependency table."""
    lines = [
        HEADER,
        "",
        "# Third-party software",
        "",
        "Direct dependencies, pinned in `pyproject.toml`. Licenses are read from the installed",
        "package metadata, not copied by hand.",
        "",
        "| package | pinned version | license |",
        "|---|---|---|",
    ]
    for row in rows:
        lines.append(f"| `{row['name']}` | {row['pinned']} | {row['license']} |")
    lines += [
        "",
        "These packages are used unmodified, as libraries; none of their source is redistributed",
        "here. `brian2` carries CeCILL-2.1, the most restrictive license in the table.",
        "",
        "`numpy` is held at 2.3.5 because brian2 2.9.0 does not import against 2.4, which removed",
        "`ndarray.ptp`.",
    ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Write CITATIONS.md and THIRD_PARTY.md, or check them with --check."""
    import argparse

    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true", help="fail if the files are out of date")
    p.add_argument("--quick", action="store_true", help="accepted for run_all; no effect")
    args = p.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")

    wanted = {
        CITATIONS: render_citations(manifest_sources()),
        THIRD_PARTY: render_third_party(dependency_licenses()),
    }
    stale = [path for path, text in wanted.items() if not path.exists() or path.read_text() != text]
    if args.check:
        for path in stale:
            log.error("%s is out of date; run python -m neuromps.report.attribution", path.name)
        return 1 if stale else 0
    for path, text in wanted.items():
        path.write_text(text)
        log.info("wrote %s", path.name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
