"""Generate `outputs/DATA_CARD.md` from the built asset and the raw manifest.

Every number here is read from `data/processed/` and `data/raw/MANIFEST.json`;
nothing is typed in by hand.
"""

import argparse
import json
import logging
from pathlib import Path

import pandas as pd

from neuromps.fetch.manifest import Manifest
from neuromps.metrics import update_metrics

log = logging.getLogger("neuromps.qc")
REPO_ROOT = Path(__file__).resolve().parents[3]
PROCESSED = REPO_ROOT / "data" / "processed"
RAW_ROOT = REPO_ROOT / "data" / "raw"
CARD_PATH = REPO_ROOT / "outputs" / "DATA_CARD.md"
FEATURE_COLUMNS = [
    "features.mfr_hz",
    "features.burst_rate_per_min",
    "features.burst_duration_s",
    "features.spikes_per_burst",
    "features.pct_spikes_in_bursts",
    "features.network_burst_rate_per_min",
    "features.synchrony_index",
    "features.isi_cv",
    "features.active_electrodes",
]


def _table(df: pd.DataFrame) -> str:
    """Markdown table from a dataframe with its index as the first column."""
    return df.to_markdown()


def source_table(df: pd.DataFrame, manifest: Manifest) -> pd.DataFrame:
    """Records, level, species and license per source."""
    rows = []
    for source, part in df.groupby("source"):
        rec = manifest.sources.get(source)
        rows.append(
            {
                "source": source,
                "records": len(part),
                "data levels": ", ".join(sorted(part["data_level"].unique())),
                "species": ", ".join(sorted(part["cell_source.species"].unique())),
                "usable": int(part["qc.usable"].sum()),
                "license": rec.license if rec else "unknown",
            }
        )
    return pd.DataFrame(rows).set_index("source")


def feature_coverage(df: pd.DataFrame) -> pd.DataFrame:
    """Percent of records per source with a non-null value for each core feature."""
    present = [c for c in FEATURE_COLUMNS if c in df.columns]
    cover = df.groupby("source")[present].apply(lambda g: g.notna().mean() * 100)
    cover.columns = [c.removeprefix("features.") for c in cover.columns]
    return cover.round(0).astype(int)


def flag_counts(df: pd.DataFrame) -> pd.DataFrame:
    """How often each QC flag fires, by source."""
    exploded = (
        df.assign(flag=df["qc.flags"].fillna("").str.split(";"))
        .explode("flag")
        .query("flag != ''")
        .reset_index(drop=True)  # explode duplicates index labels, which crosstab rejects
    )
    if exploded.empty:
        return pd.DataFrame()
    return pd.crosstab(exploded["flag"], exploded["source"])


def build_card(processed: Path = PROCESSED, raw_root: Path = RAW_ROOT) -> str:
    """Render the data card as markdown."""
    df = pd.read_parquet(processed / "neuromps.parquet")
    manifest = Manifest.load(raw_root / "MANIFEST.json")
    provenance = json.loads((processed / "provenance.json").read_text())
    skipped = [s for s in manifest.sources.values() if s.status == "skipped"]
    flags = flag_counts(df)
    return "\n".join(
        [
            "# NeuroMPS data asset — data card",
            "",
            "Generated by `python -m neuromps.qc.data_card`. Research decision-support only; "
            "no efficacy, safety, diagnostic or clinical claims.",
            "",
            f"- Records: **{len(df):,}**, built {provenance['generated_at']}",
            f"- Schema: `{provenance['schema']}`; conformance level 2 enforced at build time",
            f"- Usable: **{int(df['qc.usable'].sum()):,}**; flagged unusable: "
            f"{int((~df['qc.usable'].astype(bool)).sum()):,}",
            "",
            "## Sources",
            "",
            _table(source_table(df, manifest)),
            "",
            "## Feature coverage (% of records with a value)",
            "",
            "A source that cannot support a feature records null rather than a "
            "substitute, so these gaps are the honest shape of the asset.",
            "",
            _table(feature_coverage(df)),
            "",
            "## QC flags",
            "",
            _table(flags) if not flags.empty else "_No flags set._",
            "",
            "## Sources considered and excluded",
            "",
            *(f"- **{s.name}** ({s.license}): {s.note}" for s in skipped),
            "" if skipped else "_None._",
            "",
            "## Limitations",
            "",
            "- Spike detection is the publishers', not ours, in every source.",
            "- Records are comparable only within a data level "
            "(see `schema/STANDARD.md` section 3).",
            "- Electrode counts differ by orders of magnitude across platforms; "
            "electrode-dependent features must not be compared without explicit rescaling.",
            "- QC flags are informational: a flagged record is not automatically excluded.",
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    """Write the data card and record its headline counts in metrics.json."""
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--out", type=Path, default=CARD_PATH)
    args = p.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    card = build_card()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(card)
    df = pd.read_parquet(PROCESSED / "neuromps.parquet")
    flags = flag_counts(df)
    update_metrics(
        "data_card",
        {
            "records": int(len(df)),
            "usable": int(df["qc.usable"].sum()),
            "flag_counts": {k: int(v) for k, v in flags.sum(axis=1).items()}
            if not flags.empty
            else {},
        },
    )
    log.info("wrote %s (%d lines)", args.out, card.count("\n"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
